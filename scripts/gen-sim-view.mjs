// Writes src/sim/viewAccessors.ts: one typed getter/setter per key in OP_KEYS and GAME_KEYS
// (src/sim/view.ts). Plain class accessors give each field its own inline cache without eval.
// Run `pnpm run gen:view` after changing either list; src/sim/view.test.ts fails until you do.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const VIEW = 'src/sim/view.ts';
const OUT = 'src/sim/viewAccessors.ts';

function keys(src, name) {
  const m = src.match(new RegExp(`export const ${name} = \\[([^\\]]*)\\]`));
  if (!m) throw new Error(`${name} not found in ${VIEW}`);
  return [...m[1].matchAll(/'(\w+)'/g)].map((x) => x[1]);
}

const src = readFileSync(VIEW, 'utf8');
const accessors = (owner, type, list) =>
  list
    .map(
      (k) =>
        `  get ${k}(): ${type}['${k}'] {\n    return this.${owner}.${k};\n  }\n` +
        `  set ${k}(v: ${type}['${k}']) {\n    this.${owner}.${k} = v;\n  }`,
    )
    .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/gen-sim-view.mjs from OP_KEYS and GAME_KEYS in view.ts. Do not edit.
import type { GameState, Operation } from './types';

/** A \`Sim\` over one GameState and one Operation; every access site gets its own inline cache. */
export class SimView {
  constructor(
    readonly g: GameState,
    readonly op: Operation,
  ) {}
${accessors('g', 'GameState', keys(src, 'GAME_KEYS'))}
${accessors('op', 'Operation', keys(src, 'OP_KEYS'))}
}
`,
);
execFileSync('node_modules/.bin/oxfmt', [OUT], { stdio: 'inherit' });
